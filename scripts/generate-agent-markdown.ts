/**
 * Emits the Markdown representation of every page as a static file under
 * `public/md/`, and the route list the proxy needs to find them.
 *
 * Why static files and not just the /md route handler: Next sets its own
 * `Vary: rsc, next-router-state-tree, ...` on every App Router response,
 * replacing whatever `headers()` in next.config.mjs configured. A response
 * served straight from `public/` never reaches that code, so it keeps the
 * `Vary: Accept, Accept-Encoding` that content negotiation requires
 * (acceptmarkdown.com). The route handler stays as the 404 fallback.
 *
 * Runs from `bun run build` before `next build`.
 */
import fs from "node:fs";
import path from "node:path";
import {
  renderHome,
  renderBlogIndex,
  renderBlogPost,
  renderProjects,
  renderDailyDrivers,
} from "@/lib/agent-markdown";
import { getBlogSlugs } from "@/lib/blog";

const OUT_DIR = path.join(process.cwd(), "public/md");
const ROUTES_FILE = path.join(process.cwd(), "src/lib/markdown-routes.generated.ts");

function write(relative: string, body: string): void {
  const target = path.join(OUT_DIR, relative);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, body.endsWith("\n") ? body : `${body}\n`);
}

fs.rmSync(OUT_DIR, { recursive: true, force: true });

write("index.md", renderHome());
write("blog.md", renderBlogIndex());
write("projects.md", renderProjects());
write("daily-drivers.md", renderDailyDrivers());

const slugs = getBlogSlugs().sort();
for (const slug of slugs) {
  const body = renderBlogPost(slug);
  if (body) write(`blog/${slug}.md`, body);
}

fs.writeFileSync(
  ROUTES_FILE,
  `// Generated by scripts/generate-agent-markdown.ts. Do not edit by hand.
// Lists the paths that have a prebuilt Markdown twin under public/md/, so the
// proxy can rewrite to the static file instead of the /md route handler.

export const MARKDOWN_BLOG_SLUGS: ReadonlySet<string> = new Set([
${slugs.map((slug) => `  ${JSON.stringify(slug)},`).join("\n")}
]);
`
);

console.log(
  `Wrote ${slugs.length + 4} markdown files to public/md and ${slugs.length} slugs to markdown-routes.generated.ts`
);
