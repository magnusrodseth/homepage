// Writes the handwritten signatures as SVG stroke paths for <Signature>.
//
//   bun run signature:generate
//
// The letters come from EMS Allure, a single-stroke script font by Evil Mad
// Scientist (SIL Open Font License), shipped as an SVG font in the hersheytext
// package. A single-stroke font stores the centre line of each pen stroke, not
// an outline, which is what lets the browser "write" it with a dash
// animation. The font has no "ø", so the script writes an "o" and adds the
// slash as a last stroke, the way a hand crosses a "t" after the word.
//
// Output: src/lib/signature.generated.ts. Commit it; the site never fetches
// the font at runtime. Re-run after changing SIGNATURES or the layout knobs.

import { writeFileSync } from "node:fs";

const FONT_URL =
  "https://unpkg.com/hersheytext@2.0.0/svg_fonts/EMSAllure.svg";
const OUT = "src/lib/signature.generated.ts";

const SIGNATURES = {
  name: "Magnus Rødseth",
  initials: "MR",
};

const TRACKING = 30; // extra advance per letter, font units
// Extra advance after single letters. The "d" ascender loops back over the next
// letter, which made "ds" read as one glyph.
const KERN = { d: 120 };
const JOIN = 60; // merge a letter's first stroke into the previous one when closer than this
const PAD = 40; // viewBox padding, so round caps are not clipped

const res = await fetch(FONT_URL);
if (!res.ok) throw new Error(`Fetching ${FONT_URL} failed: ${res.status}`);
const src = await res.text();
const glyphs = {};
for (const m of src.matchAll(
  /<glyph\s+unicode="([^"]+)"[^>]*?horiz-adv-x="([\d.-]+)"(?:[^>]*?d="([^"]*)")?/g
)) {
  const strokes = (m[3] ?? "")
    .split("M")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => s.split("L").map((p) => p.trim().split(/\s+/).map(Number)));
  glyphs[m[1]] = { adv: Number(m[2]), strokes };
}

function layout(text) {
  let x = 0;
  const strokes = [];
  const late = [];
  for (const ch of text) {
    const g = glyphs[ch === "ø" ? "o" : ch];
    if (!g) throw new Error(`EMS Allure has no glyph for "${ch}"`);
    for (const stroke of g.strokes) {
      // Font units are y-up; SVG is y-down.
      const pts = stroke.map(([px, py]) => [px + x, -py]);
      const prev = strokes.at(-1);
      const gap = prev && dist(prev.at(-1), pts[0]);
      if (gap !== undefined && gap < JOIN) prev.push(...pts.slice(1));
      else strokes.push(pts);
    }
    if (ch === "ø") late.push([[x - 40, 10], [x + 270, -380]]);
    x += g.adv + (ch === " " ? 0 : TRACKING) + (KERN[ch] ?? 0);
  }
  return [...strokes, ...late];
}

const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1]);
const round = (n) => Math.round(n * 10) / 10;

// Catmull-Rom through the font's polyline points, as cubic Béziers.
function smooth(pts) {
  let d = `M${round(pts[0][0])} ${round(pts[0][1])}`;
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[i - 1] ?? pts[i];
    const p1 = pts[i];
    const p2 = pts[i + 1];
    const p3 = pts[i + 2] ?? p2;
    const c = [
      p1[0] + (p2[0] - p0[0]) / 6,
      p1[1] + (p2[1] - p0[1]) / 6,
      p2[0] - (p3[0] - p1[0]) / 6,
      p2[1] - (p3[1] - p1[1]) / 6,
      p2[0],
      p2[1],
    ];
    d += `C${c.map(round).join(" ")}`;
  }
  return d;
}

const out = {};
for (const [key, text] of Object.entries(SIGNATURES)) {
  const strokes = layout(text);
  const all = strokes.flat();
  const xs = all.map((p) => p[0]);
  const ys = all.map((p) => p[1]);
  const [x0, y0] = [Math.min(...xs) - PAD, Math.min(...ys) - PAD];
  const [w, h] = [Math.max(...xs) - x0 + PAD, Math.max(...ys) - y0 + PAD];
  const lengths = strokes.map((s) =>
    s.slice(1).reduce((sum, p, i) => sum + dist(s[i], p), 0)
  );
  const total = lengths.reduce((a, b) => a + b, 0);
  let acc = 0;
  out[key] = {
    text,
    viewBox: [x0, y0, w, h].map(round).join(" "),
    strokes: strokes.map((s, i) => {
      const start = acc / total;
      acc += lengths[i];
      return {
        d: smooth(s),
        start: Math.round(start * 1e4) / 1e4,
        share: Math.round((lengths[i] / total) * 1e4) / 1e4,
      };
    }),
  };
}

writeFileSync(
  OUT,
  `// Generated by scripts/generate-signature.mjs. Do not edit by hand.
// Letterforms: EMS Allure by Evil Mad Scientist, SIL Open Font License.

export type SignatureStroke = {
  /** SVG path data, in viewBox units. */
  d: string;
  /** Where this stroke starts, as a fraction of the whole signature's ink. */
  start: number;
  /** This stroke's share of the whole signature's ink. */
  share: number;
};

export const SIGNATURES = ${JSON.stringify(out, null, 2)} as const satisfies Record<
  string,
  { text: string; viewBox: string; strokes: readonly SignatureStroke[] }
>;

export type SignatureName = keyof typeof SIGNATURES;
`
);
console.log(`Wrote ${OUT}: ${Object.keys(out).join(", ")}`);
